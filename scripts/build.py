#!/usr/bin/env python3
"""Validate the archive and publish an explicit, clean public file set."""
import datetime as dt
import json
import re
import shutil
import tempfile
from pathlib import Path
try:
    from scripts.editorial import apply_editorial
except ModuleNotFoundError:
    from editorial import apply_editorial

ROOT=Path(__file__).resolve().parents[1]
PUBLIC_ASSETS=('styles.css','app.js','favicon.svg','data.js','theme.js','editorial-art.svg','aero-landscape.svg')


def validate_issue(issue,week_id):
    if not re.fullmatch(r'\d{4}-W\d{2}',week_id) or issue.get('id')!=week_id:
        raise ValueError(f'Invalid week ID: {week_id}')
    start=dt.date.fromisoformat(issue['from_date']);end=dt.date.fromisoformat(issue['to_date'])
    year,week,_=start.isocalendar()
    if start.weekday()!=0 or end-start!=dt.timedelta(days=6) or week_id!=f'{year}-W{week:02d}':
        raise ValueError(f'Invalid date window: {week_id}')
    articles=issue['articles'];ids=set()
    if not isinstance(articles,list) or not articles:raise ValueError(f'Empty issue: {week_id}')
    for article in articles:
        if article['id'] in ids:raise ValueError(f'Duplicate article ID: {article["id"]}')
        ids.add(article['id'])
        if not article.get('title') or not article.get('url','').startswith('https://'):
            raise ValueError(f'Invalid bibliography: {article["id"]}')
        if not start<=dt.date.fromisoformat(article['date'])<=end:
            raise ValueError(f'Out-of-week paper: {article["id"]}')
    for note in issue.get('deepdives',[]):
        if note.get('id') not in ids:raise ValueError(f'Unknown deep dive ID in {week_id}')


def build(root=ROOT):
    index=json.loads((root/'data/index.json').read_text(encoding='utf-8'))
    issues={}
    for path in sorted((root/'data/weeks').glob('*.json'),reverse=True):
        source=path.read_bytes();issue=json.loads(source)
        validate_issue(issue,path.stem)
        editorial_path=root/'data/editorial'/path.name
        supplement=json.loads(editorial_path.read_text(encoding='utf-8')) if editorial_path.exists() else None
        issues[path.stem]=apply_editorial(issue,supplement,source)
        validate_issue(issues[path.stem],path.stem)
    if not issues:raise ValueError('No weekly archives found')
    missing={w['id'] for w in index['weeks']}-issues.keys()
    if missing:raise ValueError(f'Manifest references missing archives: {sorted(missing)}')
    # Rebuild the manifest from immutable issues, recovering an interrupted index update.
    index['weeks']=[dict(id=w['id'],title=w['title'],from_date=w['from_date'],to_date=w['to_date'],
                        count=len(w['articles']),curation=w.get('curation','自动收录')) for w in issues.values()]
    payload=json.dumps({'index':index,'issues':issues},ensure_ascii=False,separators=(',',':')).replace('</','<\\/')
    bundle='/* Generated by scripts/build.py — do not edit manually. */\nwindow.RADAR_DATA='+payload+';\n'
    # Never copy arbitrary files, credentials or stale artifacts into the public site.
    with tempfile.TemporaryDirectory(dir=root,prefix='.radar-build-') as tmp:
        stage=Path(tmp)/'dist';(stage/'assets').mkdir(parents=True);(stage/'data/weeks').mkdir(parents=True)
        shutil.copy2(root/'index.html',stage/'index.html')
        for name in PUBLIC_ASSETS:
            if name=='data.js':(stage/'assets'/name).write_text(bundle,encoding='utf-8')
            else:shutil.copy2(root/'assets'/name,stage/'assets'/name)
        for week_id,issue in issues.items():
            (stage/'data/weeks'/f'{week_id}.json').write_text(json.dumps(issue,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
        (stage/'data/index.json').write_text(json.dumps(index,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
        (stage/'.nojekyll').touch()
        dist=root/'dist'
        if dist.is_symlink():raise ValueError('dist must not be a symbolic link')
        if dist.exists():shutil.rmtree(dist)
        stage.rename(dist)
    (root/'assets/data.js').write_text(bundle,encoding='utf-8')
    (root/'data/index.json').write_text(json.dumps(index,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    print(f'Validated {len(issues)} weekly issues. Prepared public-only deployment: {root/"dist"}')


if __name__=='__main__':build()
